/** Grammatically correct "years" word for the given count, e.g. "6 years" / "6 godina". */
export function yearsWord(lang: Lang, years: number): string {
	if (lang === 'en') return years === 1 ? 'year' : 'years';

	const mod10 = years % 10;
	const mod100 = years % 100;
	if (mod10 === 1 && mod100 !== 11) return 'godinu';
	if (mod10 >= 2 && mod10 <= 4 && !(mod100 >= 12 && mod100 <= 14)) return 'godine';
	return 'godina';
}
